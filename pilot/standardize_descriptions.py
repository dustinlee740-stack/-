df = pd.read_excel(OUT)

# Remove orphan column accidentally created by an earlier script run.
if "한글 설명" in df.columns and "Korean Description" in df.columns:
    df = df.drop(columns=["한글 설명"])

# Apply standardization
applied = 0
missing = []
for idx, row in df.iterrows():
    name = row["Name"]
    if name in STD:
        df.at[idx, "Korean Description"] = STD[name][0]
        df.at[idx, "English Description"] = STD[name][1]
        applied += 1
    else:
        missing.append(name)

# Re-sort to keep alphabetical order (case-insensitive ASCII)
df = df.sort_values(by="Name", key=lambda s: s.str.upper(), kind="stable").reset_index(drop=True)

# Drop legacy single-Category column if present (replaced by 3-level hierarchy)
if "Category" in df.columns:
    df = df.drop(columns=["Category"])

# Insert 3-level category columns right after English Description
def _hier(name, idx):
    h = HIERARCHY.get(name)
    return h[idx] if h else ""

df["대분류"] = df["Name"].apply(lambda n: _hier(n, 0))
df["중분류"] = df["Name"].apply(lambda n: _hier(n, 1))
df["소분류"] = df["Name"].apply(lambda n: _hier(n, 2))
cols = list(df.columns)
for c in ("대분류", "중분류", "소분류"):
    cols.remove(c)
ins = cols.index("English Description") + 1
for c in ("소분류", "중분류", "대분류"):  # insert in reverse so order ends up 대→중→소
    cols.insert(ins, c)
df = df[cols]

uncat = df[df["대분류"] == ""]["Name"].tolist()

with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    df.to_excel(writer, index=False, sheet_name="Components")
    ws = writer.sheets["Components"]

    base_widths = {"Name": 16, "Full Name": 38,
                   "Korean Description": 60, "English Description": 60,
                   "대분류": 14, "중분류": 18, "소분류": 22,
                   "Category": 26,
                   "Portal Name": 28, "Portal URL": 50}
    for col_idx, col_name in enumerate(df.columns, start=1):
        letter = ws.cell(row=1, column=col_idx).column_letter
        ws.column_dimensions[letter].width = base_widths.get(col_name, 24)

    header_font = Font(bold=True)
    header_fill = PatternFill("solid", fgColor="DDEBF7")
    for cell in ws[1]:
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    wrap = Alignment(wrap_text=True, vertical="top")
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row, min_col=1, max_col=ws.max_column):
        for cell in row:
            cell.alignment = wrap

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

