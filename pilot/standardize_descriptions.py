def kr(purpose, functions, domain, related="", status=""):
    parts = [f"{K}: {purpose}", f"{F}:"]
    parts += [f"- {fn}" for fn in functions]
    parts.append(f"{D}: {domain}")
    if related:
        parts.append(f"{R}: {related}")
    if status:
        parts.append(f"{S}: {status}")
    return "\n".join(parts)


